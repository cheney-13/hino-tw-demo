def _val(m, key):
    if isinstance(m, str):
        return f"寬座艙自排 {m}" if key == "label" else "—"
    if key == "label":
        return f'{m["name"]} {m["id"]}'
    return key[1:] if key.startswith("=") else m[key]

def models(ton):
    return [dict(name="寬座艙自排", id=m) if isinstance(m, str) else dict(name=m["name"], id=m["id"]) for m in TON_MODELS[ton]]

def sections(ton):
    ms = TON_MODELS[ton]
    return [(g, [(k, [_val(m, key) for m in ms]) for k, key in rows]) for g, rows in LAYOUT]

